/**
 * Internationalization & Currency Formatting Dictionary
 * Clean client-side locale dictionary supporting EN, FR, ES, and DE.
 */

import { SupportedLocale, SupportedCurrency } from '../types';

export const CURRENCY_SYMBOLS: Record<SupportedCurrency, string> = {
  USD: '$',
  EUR: '€',
  GBP: '£',
  GHS: 'GH₵',
  NGN: '₦',
  CAD: 'CA$',
};

export function formatCurrency(amount: number, currency: SupportedCurrency = 'USD'): string {
  const symbol = CURRENCY_SYMBOLS[currency] || '$';
  return `${symbol}${amount.toLocaleString()}`;
}

