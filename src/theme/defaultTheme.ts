/**
 * Utility to convert hex to RGB values
 */
export function hexToRgb(hex: string): string {
  const cleanHex = hex.replace('#', '');
  if (cleanHex.length === 3) {
    const r = parseInt(cleanHex[0] + cleanHex[0], 16);
    const g = parseInt(cleanHex[1] + cleanHex[1], 16);
    const b = parseInt(cleanHex[2] + cleanHex[2], 16);
    return `${r}, ${g}, ${b}`;
  }
  if (cleanHex.length === 6) {
    const r = parseInt(cleanHex.substring(0, 2), 16);
    const g = parseInt(cleanHex.substring(2, 4), 16);
    const b = parseInt(cleanHex.substring(4, 6), 16);
    return `${r}, ${g}, ${b}`;
  }
  return '245, 158, 11';
}

/**
 * Calculate WCAG contrast ratio between two hex colors
 */
export function calculateContrast(hex1: string, hex2: string): number {
  const getLuminance = (hex: string) => {
    const clean = hex.replace('#', '');
    const r = parseInt(clean.substring(0, 2) || '0', 16) / 255;
    const g = parseInt(clean.substring(2, 4) || '0', 16) / 255;
    const b = parseInt(clean.substring(4, 6) || '0', 16) / 255;
    const a = [r, g, b].map(v => (v <= 0.03928 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4)));
    return a[0] * 0.2126 + a[1] * 0.7152 + a[2] * 0.0722;
  };
  const lum1 = getLuminance(hex1);
  const lum2 = getLuminance(hex2);
  const brightest = Math.max(lum1, lum2);
  const darkest = Math.min(lum1, lum2);
  return (brightest + 0.05) / (darkest + 0.05);
}

/**
 * Apply theme tokens to DOM root
 */
export function applyThemeToDom(theme: ThemeSettings) {
  const root = document.documentElement;
  const { colors, glass, typography, layout } = theme;

  root.style.setProperty('--brand-primary', colors.primary);
  root.style.setProperty('--brand-primary-rgb', hexToRgb(colors.primary));
  root.style.setProperty('--brand-secondary', colors.secondary);
  root.style.setProperty('--brand-accent', colors.accent);
  root.style.setProperty('--brand-bg', colors.background);
  root.style.setProperty('--brand-surface', colors.surface);
  root.style.setProperty('--brand-surface-elevated', colors.surfaceElevated);
  root.style.setProperty('--brand-text', colors.textPrimary);
  root.style.setProperty('--brand-text-secondary', colors.textSecondary);
  root.style.setProperty('--brand-text-muted', colors.textMuted);
  root.style.setProperty('--brand-border', colors.border);
  root.style.setProperty('--brand-button', colors.button);
  root.style.setProperty('--brand-button-text', colors.buttonText);

  root.style.setProperty('--glass-blur', `${glass.blur}px`);
  root.style.setProperty('--glass-opacity', `${glass.opacity}`);
  root.style.setProperty('--glass-border-opacity', `${glass.borderOpacity}`);
  root.style.setProperty('--card-radius', `${layout.cardRadius}px`);
  root.style.setProperty('--button-radius', `${layout.buttonRadius}px`);
  root.style.setProperty('--border-thickness', `${layout.borderThickness ?? 2}px`);

  const shadowIntensity = layout.shadowIntensity ?? 'brutalist';
  let brutalistShadow = '4px 4px 0px var(--brand-border)';
  let accentShadow = '4px 4px 0px var(--brand-primary)';

  if (shadowIntensity === 'hard') {
    brutalistShadow = '4px 4px 0px rgba(0,0,0,0.85)';
    accentShadow = '4px 4px 0px var(--brand-primary)';
  } else if (shadowIntensity === 'subtle') {
    brutalistShadow = '0 10px 30px -5px rgba(0,0,0,0.5)';
    accentShadow = '0 8px 25px -4px rgba(var(--brand-primary-rgb), 0.4)';
  } else if (shadowIntensity === 'none') {
    brutalistShadow = 'none';
    accentShadow = 'none';
  }

  root.style.setProperty('--brutalist-shadow', brutalistShadow);
  root.style.setProperty('--brutalist-accent-shadow', accentShadow);

  root.style.setProperty('--font-heading', `"${typography.headingFont}", sans-serif`);
  root.style.setProperty('--font-body', `"${typography.bodyFont}", sans-serif`);
  root.style.setProperty('--font-nav', `"${typography.navFont}", sans-serif`);
  root.style.setProperty('--font-button', `"${typography.buttonFont}", sans-serif`);
  root.style.setProperty('--heading-weight', typography.headingWeight);
  root.style.setProperty('--heading-scale', `${typography.headingScale}`);
}
